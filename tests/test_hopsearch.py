"""
Tests for the pure-Python hop search. These need no Sage.
"""
import itertools
import random

import pytest

from leaper import hopsearch as hs


def random_adjacency(rng, max_n=7):
    n = rng.randint(0, max_n)
    directed = rng.random() < 0.4
    density = rng.choice([0.3, 0.5, 0.8])
    edges = [
        (i, j) for i in range(n) for j in range(n)
        if (i != j or rng.random() < 0.1)       # occasional loops
        and (directed or i <= j)
        and rng.random() < density
    ]
    return hs.adjacency(n, edges, directed)


def brute_force_hops(adj):
    n = len(adj)
    return [p for p in itertools.permutations(range(n))
            if all(p[v] in adj[v] for v in range(n))]


def generated_group(gens, n):
    """The set of elements of the group generated by ``gens`` (small groups only)."""
    identity = tuple(range(n))
    elements = {identity}
    frontier = [identity]
    while frontier:
        new = []
        for x in frontier:
            for g in gens:
                y = hs.compose(x, g)
                if y not in elements:
                    elements.add(y)
                    new.append(y)
        frontier = new
    return elements


def cycle(n):
    return hs.adjacency(n, [(i, (i + 1) % n) for i in range(n)])


def complete(n):
    return hs.adjacency(n, [(i, j) for i in range(n) for j in range(i + 1, n)])


def grid(rows, cols):
    edges = []
    for r in range(rows):
        for c in range(cols):
            v = r * cols + c
            if c + 1 < cols:
                edges.append((v, v + 1))
            if r + 1 < rows:
                edges.append((v, v + cols))
    return hs.adjacency(rows * cols, edges)


def test_matches_brute_force_on_random_graphs():
    rng = random.Random(0)
    for _ in range(500):
        adj = random_adjacency(rng)
        expected = brute_force_hops(adj)
        assert list(hs.iter_hops(adj)) == expected      # same hops, same order
        assert hs.has_hop(adj) == bool(expected)
        assert hs.first_hop(adj) == (expected[0] if expected else None)
        found = hs.find_hop(adj)
        assert (found is not None) == bool(expected)
        if found is not None:
            assert hs.is_hop(adj, found)
            assert hs.is_hop(adj, hs.find_hop(adj, random.Random(7)))


def test_hop_counts_match_database(database):
    for entry in database:
        adj = hs.adjacency(entry["n"], entry["edges"])
        count = sum(1 for _ in hs.iter_hops(adj))
        assert count == entry["hopCount"], entry["id"]
        assert hs.has_hop(adj) == entry["hasHop"], entry["id"]


def test_known_hop_counts():
    assert len(hs.hops(cycle(8))) == 4
    assert len(hs.hops(complete(8))) == 14833          # derangements of 8
    assert len(hs.hops(grid(4, 4))) == 36 ** 2         # (perfect matchings)^2
    assert hs.hops(grid(5, 5)) == []                   # the frog puzzle
    assert hs.hops([]) == [()]


def test_large_graphs_are_fast():
    # Each of these would take longer than the age of the universe by
    # checking all n! permutations.
    assert len(hs.hops(cycle(60))) == 4
    assert not hs.has_hop(grid(7, 7))
    assert len(hs.hops(complete(14), limit=1000)) == 1000
    assert hs.is_hop(grid(10, 10), hs.find_hop(grid(10, 10)))


def test_adversarial_labeling_is_fast():
    # A bipartite "half graph" with a unique hop, labeled so that the vertex
    # with the most choices comes first. Without pruning this explores about
    # 15! dead ends.
    m = 15
    edges = [(m - 1 - i, m + j) for i in range(m) for j in range(i + 1)]
    assert len(hs.hops(hs.adjacency(2 * m, edges))) == 1


def test_is_hop_rejects_non_permutations():
    adj = cycle(4)
    assert hs.is_hop(adj, (1, 2, 3, 0))
    assert not hs.is_hop(adj, (2, 3, 0, 1))     # not along edges
    assert not hs.is_hop(adj, (1, 0, 1, 0))     # along edges, but not injective
    assert not hs.is_hop(adj, (1, 2, 3))        # wrong length


def test_directed_hops():
    directed_cycle = hs.adjacency(3, [(0, 1), (1, 2), (2, 0)], directed=True)
    assert hs.hops(directed_cycle) == [(1, 2, 0)]


@pytest.mark.parametrize("n", [1, 2, 3, 4])
def test_leap_generators_generate_all_products(n):
    rng = random.Random(n)
    checked = 0
    while checked < 25:
        adj = random_adjacency(rng, max_n=6)
        hops = hs.hops(adj)
        if not hops or len(hops) ** n > 4000:
            continue
        checked += 1
        products = hops
        for _ in range(n - 1):
            products = [hs.compose(p, q) for p in products for q in hops]
        expected = generated_group(products, len(adj))
        assert generated_group(hs.leap_generators(hops, n), len(adj)) == expected


def test_leap_group_orders_match_database(database_sample):
    checked = 0
    for entry in database_sample:
        if not entry["hasHop"] or entry["l1Order"] > 1500:
            continue
        adj = hs.adjacency(entry["n"], entry["edges"])
        hops = hs.hops(adj)
        for n, key in ((1, "l1Order"), (2, "l2Order")):
            group = generated_group(hs.leap_generators(hops, n), entry["n"])
            assert len(group) == entry[key], (entry["id"], n)
        checked += 1
    assert checked > 200


def test_order_bound_holds_on_database(database):
    for entry in database:
        adj = hs.adjacency(entry["n"], entry["edges"])
        for n, key in ((1, "l1Order"), (2, "l2Order"), (3, "l1Order")):
            assert hs.order_bound(adj, n) % entry[key] == 0, (entry["id"], n)


def test_order_bound_examples():
    assert hs.order_bound(complete(5)) == 120
    assert hs.order_bound(cycle(6), 1) == 2 * 6 * 6     # bipartite: sides swap
    assert hs.order_bound(cycle(6), 2) == 6 * 6
    assert hs.order_bound(cycle(5), 1) == 120            # odd cycle: no sides
    two_triangles = hs.adjacency(6, [(0, 1), (1, 2), (2, 0), (3, 4), (4, 5), (5, 3)])
    assert hs.order_bound(two_triangles) == 36
