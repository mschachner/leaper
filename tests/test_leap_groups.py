"""
Tests for the Sage layer (leap groups via GAP). Skipped where Sage is not
installed; run them with ``sage -python -m pytest`` or inside the backend's
Docker image.
"""
import random

import pytest

pytest.importorskip("sage.all")

from sage.all import DiGraph, Graph, PermutationGroup, graphs, libgap

from leaper import hopsearch as hs
from leaper import leaper as L


def sage_graph(n, edges):
    return Graph([list(range(n)), [tuple(e) for e in edges]], format="vertices_and_edges")


def grid(rows, cols):
    return graphs.GridGraph([rows, cols]).relabel(inplace=False)


def leap(G, n=1):
    _, adj = L._adjacency(G)
    group, info = L.leap_group_from_adjacency(adj, n)
    return group, info, len(adj)


def test_hops_are_standard_permutations_in_lex_order():
    h = L.hops(graphs.CycleGraph(4))
    assert [list(p) for p in h] == [[2, 1, 4, 3], [2, 3, 4, 1], [4, 1, 2, 3], [4, 3, 2, 1]]
    assert all(L.is_hop(graphs.CycleGraph(4), [x - 1 for x in p]) for p in h)


def test_leap_n_matches_definition_on_random_graphs():
    """leap_n(G, n) is the group generated by all products of n hops."""
    rng = random.Random(3)
    checked = 0
    while checked < 60:
        n = rng.randint(2, 7)
        p = rng.choice([0.4, 0.6, 0.9])
        if rng.random() < 0.35:
            G = DiGraph([list(range(n)), [(i, j) for i in range(n) for j in range(n)
                                          if i != j and rng.random() < p]],
                        format="vertices_and_edges")
        else:
            G = sage_graph(n, [(i, j) for i in range(n) for j in range(i + 1, n)
                               if rng.random() < p])
        h = L.hops(G)
        for k in (1, 2, 3):
            if not h or len(h) ** k > 5000:
                continue
            expected = PermutationGroup(L.compositions(h, k), domain=range(1, n + 1))
            got = L.leap_n(G, k)
            assert got.order() == expected.order()
            assert all(got(g) in got for g in expected.gens())
            checked += 1


def test_leap_group_orders_match_database(database_sample):
    for entry in database_sample:
        G = sage_graph(entry["n"], entry["edges"])
        assert int(L.leap_n(G, 1).order()) == entry["l1Order"], entry["id"]
        assert int(L.leap_n(G, 2).order()) == entry["l2Order"], entry["id"]


def test_leap_redundant_edges_match_database(database_sample):
    for entry in database_sample:
        G = sage_graph(entry["n"], entry["edges"])
        used = L.hop_edges(G)
        edges = sorted(sorted(e) for e in entry["edges"])
        redundant = [i for i, (u, v) in enumerate(edges)
                     if (u, v) not in used and (v, u) not in used]
        assert redundant == entry["redundant"], entry["id"]
        assert L.is_leap_minimal(G) == (not entry["redundant"])
        assert L.leap_minimal_core(G).is_connected() == entry["leapConnected"] or entry["n"] == 1


@pytest.mark.parametrize("G, n, order, name", [
    (graphs.CompleteGraph(8), 1, 40320, "S8"),
    (graphs.CompleteGraph(40), 1, None, "S40"),
    (graphs.PetersenGraph(), 1, 3628800, "S10"),
    (graphs.CompleteBipartiteGraph(3, 3), 1, 72, "S3 ≀ C2"),
    (graphs.CubeGraph(3).relabel(inplace=False), 1, 1152, "S4 ≀ C2"),
    (grid(4, 4), 1, 2 * 40320 ** 2, "S8 ≀ C2"),
    (grid(4, 4), 2, 40320 ** 2, "S8 x S8"),
    (graphs.CompleteGraph(9).disjoint_union(graphs.CompleteGraph(9)).relabel(inplace=False),
     1, 362880 ** 2, "S9 x S9"),
    (grid(5, 5), 1, 1, "1"),
    (grid(10, 10), 1, None, "S50 ≀ C2"),
])
def test_recognized_groups(G, n, order, name):
    group, info, N = leap(G, n)
    if order is not None:
        assert int(group.Order()) == order
    assert L.recognize_group(group, N) == name


def test_recognized_wreath_products_are_wreath_products():
    """Check the order argument in recognize_group against GAP directly."""
    for m, k in [(3, 2), (4, 2), (3, 3), (5, 2)]:
        W = libgap.WreathProduct(libgap.SymmetricGroup(m), libgap.SymmetricGroup(k))
        assert L.recognize_group(W, m * k) == f"S{m} ≀ {'C2' if k == 2 else f'S{k}'}"
        # An index-2 subgroup has the same blocks but must not be recognized.
        assert L.recognize_group(W.DerivedSubgroup(), m * k) != L.recognize_group(W, m * k)


def test_small_groups_keep_gap_names():
    # D8 is also C2 wr C2, and is in the database under GAP's name.
    group, _, N = leap(graphs.CycleGraph(4))
    assert L.recognize_group(group, N) is None
    assert L.describe_group(group, N) == "D8"


def test_sampling_stops_early_on_dense_graphs():
    group, info, _ = leap(graphs.CompleteGraph(12))
    assert not info["complete"] and info["hops"] < 1000   # K12 has 176,214,841 hops
    group, info, _ = leap(graphs.CycleGraph(8))
    assert info == {"hops": 4, "complete": True}
